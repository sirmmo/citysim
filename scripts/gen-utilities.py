#!/usr/bin/env python3
"""Generates the water and waste art: AC3D models (the buildings; pipes run underground) and
sidebar icons. The models are built from simple solids in tile units (x
east, y up, z south; a building of w x l tiles spans 0..w, 0..l), coloured
by material, two-sided. Run from the repository root:

    python3 scripts/gen-utilities.py

Icons need Pillow. Everything written here is CC0, like the Kenney kits.
"""
import math
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets")


class Model:
    def __init__(self):
        self.materials = []  # (r, g, b)
        self.objects = []  # (material, [vertices], [faces as index lists])

    def mat(self, rgb):
        rgb = tuple(round(c, 3) for c in rgb)
        if rgb not in self.materials:
            self.materials.append(rgb)
        return self.materials.index(rgb)

    def poly(self, rgb, verts, faces):
        self.objects.append((self.mat(rgb), verts, faces))

    def box(self, rgb, x0, y0, z0, x1, y1, z1, top=None):
        v = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1), (x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)]
        sides = [[0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7], [0, 3, 2, 1]]
        self.poly(rgb, v, sides)
        self.poly(top or rgb, v, [[4, 5, 6, 7]])

    def cylinder(self, rgb, cx, cz, r, y0, y1, n=16, top=None, r1=None):
        """A cylinder (or a frustum when r1 is given) standing on y0."""
        r1 = r if r1 is None else r1
        v = []
        for i in range(n):
            a = 2 * math.pi * i / n
            v.append((cx + r * math.cos(a), y0, cz + r * math.sin(a)))
        for i in range(n):
            a = 2 * math.pi * i / n
            v.append((cx + r1 * math.cos(a), y1, cz + r1 * math.sin(a)))
        sides = [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
        self.poly(rgb, v, sides)
        if r1 > 0.001:
            self.poly(top or rgb, v, [[n + i for i in range(n)]])

    def cone(self, rgb, cx, cz, r, y0, y1, n=16):
        v = [(cx + r * math.cos(2 * math.pi * i / n), y0, cz + r * math.sin(2 * math.pi * i / n)) for i in range(n)]
        v.append((cx, y1, cz))
        self.poly(rgb, v, [[i, (i + 1) % n, n] for i in range(n)])

    def roof(self, rgb, x0, z0, x1, z1, y0, y1):
        """A gable roof along x."""
        zm = (z0 + z1) / 2
        v = [(x0, y0, z0), (x1, y0, z0), (x1, y0, z1), (x0, y0, z1), (x0, y1, zm), (x1, y1, zm)]
        self.poly(rgb, v, [[0, 1, 5, 4], [2, 3, 4, 5], [0, 4, 3], [1, 2, 5]])

    def pipe(self, rgb, a, b, r, n=8):
        """A horizontal pipe from a to b (points at its axis), along x or z."""
        (ax, ay, az), (bx, by, bz) = a, b
        along_x = abs(bx - ax) > abs(bz - az)
        v = []
        for p in (a, b):
            for i in range(n):
                t = 2 * math.pi * i / n
                d1, d2 = r * math.cos(t), r * math.sin(t)
                v.append((p[0], p[1] + d2, p[2] + d1) if along_x else (p[0] + d1, p[1] + d2, p[2]))
        faces = [[i, (i + 1) % n, n + (i + 1) % n, n + i] for i in range(n)]
        faces += [list(range(n)), [n + i for i in range(n)]]
        self.poly(rgb, v, faces)

    def write(self, path, name):
        os.makedirs(os.path.dirname(path), exist_ok=True)
        out = ["AC3Db"]
        for (r, g, b) in self.materials:
            out.append(f'MATERIAL "m" rgb {r} {g} {b}  amb 0.2 0.2 0.2  emis 0 0 0  spec 0 0 0  shi 10  trans 0')
        out += ["OBJECT world", f"kids {len(self.objects)}"]
        for mat, verts, faces in self.objects:
            out += ["OBJECT poly", f'name "{name}"', f"numvert {len(verts)}"]
            out += [f"{x:.4f} {y:.4f} {z:.4f}" for (x, y, z) in verts]
            out.append(f"numsurf {len(faces)}")
            for f in faces:
                out += ["SURF 0x30", f"mat {mat}", f"refs {len(f)}"] + [f"{i} 0 0" for i in f]
            out.append("kids 0")
        with open(path, "w") as fh:
            fh.write("\n".join(out) + "\n")


def conf(path, name, w, l, h, about):
    with open(path, "w") as fh:
        fh.write(f"# {name}: generated by scripts/gen-utilities.py (CC0). {about}\n")
        fh.write(f"name={name}\nwidth={w}\nlength={l}\nheight={h}\n")


def save(rel, model, name, w, l, h, about):
    d = os.path.join(ROOT, "graphism", os.path.dirname(rel))
    base = os.path.basename(rel)
    model.write(os.path.join(d, base + ".ac"), name)
    conf(os.path.join(d, base + ".conf"), name, w, l, h, about)


# Colours.
CONCRETE = (0.78, 0.77, 0.74)
DARK = (0.35, 0.36, 0.38)
STEEL = (0.62, 0.66, 0.70)
PIPE = (0.25, 0.45, 0.72)
WATER = (0.30, 0.55, 0.80)
BRICK = (0.66, 0.36, 0.28)
ROOF = (0.38, 0.30, 0.28)
WHITE = (0.92, 0.93, 0.94)
GRASS = (0.42, 0.58, 0.32)
EARTH = (0.50, 0.42, 0.30)
RUST = (0.60, 0.38, 0.22)
GREEN = (0.30, 0.60, 0.35)
YELLOW = (0.90, 0.75, 0.25)
RED = (0.75, 0.25, 0.20)

def pumping_station():
    m = Model()
    m.box(CONCRETE, 0.05, 0.0, 0.05, 1.95, 0.04, 1.95)
    m.box(BRICK, 0.2, 0.04, 0.25, 1.3, 0.62, 1.2)
    m.roof(ROOF, 0.15, 0.2, 1.35, 1.25, 0.62, 0.9)
    # Intake well and pumps.
    m.cylinder(CONCRETE, 1.6, 0.55, 0.28, 0.04, 0.22, top=WATER)
    m.pipe(PIPE, (1.3, 0.3, 0.55), (1.6, 0.3, 0.55), 0.06)
    for x in (0.5, 0.95):
        m.cylinder(PIPE, x, 1.55, 0.15, 0.04, 0.4, top=STEEL)
    m.pipe(PIPE, (0.3, 0.25, 1.55), (1.9, 0.25, 1.55), 0.05)
    m.box(WHITE, 0.55, 0.04, 1.2, 0.85, 0.42, 1.22)  # door
    return m


def water_tower():
    m = Model()
    legs = [(0.25, 0.25), (0.75, 0.25), (0.75, 0.75), (0.25, 0.75)]
    for x, z in legs:
        m.box(STEEL, x - 0.035, 0.0, z - 0.035, x + 0.035, 1.05, z + 0.035)
    m.box(DARK, 0.25, 0.5, 0.235, 0.75, 0.54, 0.265)
    m.box(DARK, 0.25, 0.5, 0.735, 0.75, 0.54, 0.765)
    m.cylinder(PIPE, 0.5, 0.5, 0.05, 0.0, 1.05)
    m.cylinder(WATER, 0.5, 0.5, 0.42, 1.0, 1.55, n=20, top=WHITE)
    m.cone(WHITE, 0.5, 0.5, 0.44, 1.55, 1.8, n=20)
    return m


def water_treatment():
    m = Model()
    m.box(GRASS, 0.05, 0.0, 0.05, 2.95, 0.02, 2.95)
    for cx, cz in ((0.85, 0.85), (2.15, 0.85), (0.85, 2.15)):
        m.cylinder(CONCRETE, cx, cz, 0.62, 0.02, 0.28, n=24, top=WATER)
        m.box(STEEL, cx - 0.6, 0.29, cz - 0.03, cx + 0.6, 0.33, cz + 0.03)  # bridge
    m.box(CONCRETE, 1.6, 0.02, 1.6, 2.8, 0.55, 2.6)
    m.box(DARK, 1.55, 0.55, 1.55, 2.85, 0.6, 2.65)
    m.cylinder(STEEL, 2.6, 2.75, 0.12, 0.02, 0.8)
    m.pipe(PIPE, (1.47, 0.15, 0.85), (1.53, 0.15, 0.85), 0.06)
    m.pipe(PIPE, (0.85, 0.15, 1.47), (0.85, 0.15, 1.6), 0.06)
    return m


def dump():
    m = Model()
    m.box(EARTH, 0.05, 0.0, 0.05, 2.95, 0.03, 2.95)
    # The mound, terraced.
    m.cylinder(EARTH, 1.5, 1.45, 1.25, 0.03, 0.35, n=10, r1=1.0)
    m.cylinder((0.45, 0.40, 0.30), 1.5, 1.45, 1.0, 0.35, 0.6, n=10, r1=0.65)
    # Rubbish heaps in many colours.
    for i, (x, z, c) in enumerate([(1.1, 1.2, RED), (1.7, 1.1, YELLOW), (1.4, 1.75, GREEN), (1.9, 1.6, WHITE), (1.3, 1.45, PIPE), (1.65, 1.45, RUST)]):
        s = 0.12 + 0.03 * (i % 3)
        m.box(c, x - s, 0.55, z - s, x + s, 0.62 + s * 0.6, z + s)
    # Fence and the weighbridge hut.
    for x0, z0, x1, z1 in ((0.05, 0.05, 2.95, 0.09), (0.05, 2.91, 2.95, 2.95), (0.05, 0.05, 0.09, 2.95)):
        m.box(STEEL, x0, 0.03, z0, x1, 0.25, z1)
    m.box(WHITE, 2.35, 0.03, 0.25, 2.85, 0.35, 0.65)
    m.box(ROOF, 2.3, 0.35, 0.2, 2.9, 0.4, 0.7)
    return m


def recycling():
    m = Model()
    m.box(CONCRETE, 0.05, 0.0, 0.05, 1.95, 0.03, 1.95)
    m.box((0.40, 0.55, 0.45), 0.15, 0.03, 0.15, 1.85, 0.6, 1.0)
    m.box(DARK, 0.1, 0.6, 0.1, 1.9, 0.66, 1.05)
    m.box(DARK, 0.6, 0.03, 0.99, 1.4, 0.45, 1.02)  # doorway
    # Sorting bins.
    for i, c in enumerate((GREEN, PIPE, YELLOW, RED)):
        x = 0.25 + i * 0.42
        m.box(c, x, 0.03, 1.3, x + 0.32, 0.3, 1.8)
    return m


def incinerator():
    m = Model()
    m.box(CONCRETE, 0.05, 0.0, 0.05, 1.95, 0.03, 1.95)
    m.box((0.55, 0.52, 0.50), 0.2, 0.03, 0.2, 1.4, 0.75, 1.5)
    m.box(DARK, 0.15, 0.75, 0.15, 1.45, 0.8, 1.55)
    m.box(RUST, 0.25, 0.03, 1.5, 1.0, 0.35, 1.85)  # bunker
    m.cylinder((0.60, 0.58, 0.56), 1.65, 0.55, 0.16, 0.03, 2.2, r1=0.12)
    m.cylinder(RED, 1.65, 0.55, 0.125, 1.95, 2.05)
    m.cylinder(STEEL, 1.65, 1.35, 0.22, 0.03, 0.6, top=DARK)
    return m


def icons():
    try:
        from PIL import Image, ImageDraw
    except ImportError:
        print("Pillow missing: icons skipped")
        return
    blue, brown = (120, 175, 225), (190, 160, 110)

    def tile(bg):
        im = Image.new("RGBA", (64, 64), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        edge = tuple(int(c * 0.7) for c in bg) + (255,)
        # A rounded tile (drawn by hand: old Pillow has no rounded_rectangle).
        for inset, colour in ((2, edge), (4, bg + (255,))):
            r = 9 - (inset - 2)
            a, b = inset, 63 - inset
            d.rectangle((a + r, a, b - r, b), fill=colour)
            d.rectangle((a, a + r, b, b - r), fill=colour)
            for (x, y) in ((a, a), (b - 2 * r, a), (a, b - 2 * r), (b - 2 * r, b - 2 * r)):
                d.ellipse((x, y, x + 2 * r, y + 2 * r), fill=colour)
        return im, d

    def save_icon(name, im):
        im.save(os.path.join(ROOT, "graphism", "gui", name + ".png"))

    ink, white, water = (40, 60, 90), (245, 245, 245), (40, 110, 200)
    im, d = tile(blue)
    d.rectangle((6, 28, 58, 38), fill=(70, 110, 170))
    d.rectangle((26, 22, 38, 44), fill=(160, 170, 180), outline=ink)
    save_icon("water_pipe", im)
    im, d = tile(blue)
    d.polygon([(10, 30), (30, 16), (50, 30)], fill=(110, 80, 70))
    d.rectangle((14, 30, 46, 50), fill=(170, 90, 70))
    d.rectangle((44, 40, 58, 46), fill=(70, 110, 170))
    d.ellipse((50, 44, 60, 54), fill=water)
    save_icon("water_pump", im)
    im, d = tile(blue)
    for x in (22, 42):
        d.rectangle((x - 1, 34, x + 1, 56), fill=ink)
    d.rectangle((16, 16, 48, 34), fill=water, outline=ink)
    d.polygon([(14, 16), (32, 6), (50, 16)], fill=white, outline=ink)
    save_icon("water_tower", im)
    im, d = tile(blue)
    d.ellipse((8, 10, 32, 34), fill=(200, 200, 195), outline=ink)
    d.ellipse((13, 15, 27, 29), fill=water)
    d.ellipse((32, 30, 56, 54), fill=(200, 200, 195), outline=ink)
    d.ellipse((37, 35, 51, 49), fill=water)
    d.polygon([(40, 10), (46, 22), (34, 22)], fill=white)
    save_icon("water_treatment", im)
    im, d = tile(brown)
    d.polygon([(6, 52), (22, 26), (36, 34), (58, 52)], fill=(120, 95, 60))
    for (x, y, c) in ((20, 34, (200, 60, 50)), (30, 40, (230, 190, 60)), (40, 44, (70, 150, 80))):
        d.rectangle((x, y, x + 7, y + 6), fill=c)
    save_icon("waste_dump", im)
    im, d = tile(brown)
    cx, cy = 32, 32
    for k in range(3):
        a = k * 2 * math.pi / 3 - math.pi / 2
        b = a + 2 * math.pi / 3 - 0.5
        for w in range(6):  # a thick arc (old Pillow has no arc width)
            d.arc((12 + w, 12 + w, 52 - w, 52 - w), math.degrees(a) + 15, math.degrees(b), fill=(40, 120, 60))
        tip = (cx + 20 * math.cos(b), cy + 20 * math.sin(b))
        d.ellipse((tip[0] - 5, tip[1] - 5, tip[0] + 5, tip[1] + 5), fill=(40, 120, 60))
    save_icon("waste_recycling", im)
    im, d = tile(brown)
    d.rectangle((12, 30, 40, 54), fill=(140, 135, 130), outline=ink)
    d.rectangle((42, 12, 50, 54), fill=(150, 145, 140), outline=ink)
    d.ellipse((38, 2, 56, 14), fill=(200, 200, 200))
    d.polygon([(20, 50), (26, 38), (32, 50)], fill=(240, 140, 40))
    save_icon("waste_incinerator", im)


def main():
    save("water/pumping_station/pumping_station", pumping_station(), "Pumping station", 2, 2, 0.9, "Pumps water into the mains.")
    save("water/water_tower/water_tower", water_tower(), "Water tower", 1, 1, 1.8, "Stores water up high.")
    save("water/water_treatment/water_treatment", water_treatment(), "Water treatment plant", 3, 3, 0.8, "Cleans the sewage.")
    save("waste/dump/dump", dump(), "Landfill", 3, 3, 0.7, "Where the rubbish goes.")
    save("waste/recycling/recycling", recycling(), "Recycling centre", 2, 2, 0.66, "Sorts what can be used again.")
    save("waste/incinerator/incinerator", incinerator(), "Incinerator", 2, 2, 2.2, "Burns rubbish for power.")
    icons()


if __name__ == "__main__":
    main()
